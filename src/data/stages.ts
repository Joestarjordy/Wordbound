function buildStagesForTier(
  blueprints: StageBlueprint[],
  difficulty: DifficultyLevel
): Stage[] {
  return blueprints.map((bp, idx) => {
    const id = idx + 1;
    const encounters: Enemy[] = [
      makeCommonVariant(bp.mobs[0], difficulty, id, 0),
      makeCommonVariant(bp.mobs[1], difficulty, id, 1),
      makeCommonVariant(bp.mobs[2], difficulty, id, 2),
      makeCommonVariant(bp.mobs[3], difficulty, id, 3),
      makeBossVariant(bp, difficulty, id),
    ];

    return {
      id,
      name: bp.name,
      chapter: bp.chapter,
      biome: bp.biome,
      description: bp.description,
      storyBeat: bp.storyBeat,
      bgColors: BIOME_PALETTES[bp.biome][bp.paletteVariant],
      encounters,
    };
  });
}

