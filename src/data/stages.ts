interface StageBlueprint {
  name: string;
  chapter: string;
  biome: BiomeType;
  paletteVariant: 0 | 1;
  description: string;
  storyBeat: string;
  mobs: [string, string, string, string];
  bossKey: keyof typeof BOSS_ENEMIES;
  bossName?: string;
  bossTitle?: string;
  bossDialogue?: string;
  bossModifierOverride?: BossModifier;
}

const COMMON_PREFIXES: Record<DifficultyLevel, string[]> = {
  easy: ['Roving', 'Wild', 'Mossy', 'Crag', 'Tomb', 'Dusk', 'Bramble', 'Hollow'],
  medium: ['Ironclad', 'Vanguard', 'Cinder', 'Runic', 'Dread', 'Blood', 'Rift', 'Storm'],
  hard: ['Abyssal', 'Mythic', 'Astral', 'Sovereign', 'Cursed', 'Solar', 'Void', 'Eternal'],
};

function makeCommonVariant(
  baseKey: string,
  difficulty: DifficultyLevel,
  stageId: number,
  slotIdx: number
): Enemy {
  const base = COMMON_ENEMIES[baseKey] || COMMON_ENEMIES.goblin_scout;
  const diffScale = difficulty === 'easy' ? 1.0 : difficulty === 'medium' ? 1.2 : 1.45;
  const stageBonus = Math.round((stageId - 1) * 6 + slotIdx * 4);
  const scaledHp = Math.round(base.maxHp * diffScale) + stageBonus;
  const usePrefix = stageId > 3 && (stageId + slotIdx) % 2 === 0;
  const prefixes = COMMON_PREFIXES[difficulty];
  const prefix = prefixes[(stageId + slotIdx) % prefixes.length];

  return {
    ...base,
    id: `${base.id}_${difficulty}_s${stageId}_${slotIdx}`,
    name: usePrefix ? `${prefix} ${base.name}` : base.name,
    maxHp: scaledHp,
    pointMultiplier: Number((base.pointMultiplier + stageId * 0.02).toFixed(2)),
  };
}

function makeBossVariant(
  bp: StageBlueprint,
  difficulty: DifficultyLevel,
  stageId: number
): Enemy {
  const base = BOSS_ENEMIES[bp.bossKey];
  const diffScale = difficulty === 'easy' ? 1.0 : difficulty === 'medium' ? 1.2 : 1.4;
  const scaledHp = Math.round(base.maxHp * diffScale) + (stageId - 1) * 10;

  return {
    ...base,
    id: `${base.id}_${difficulty}_s${stageId}`,
    name: bp.bossName || base.name,
    title: bp.bossTitle || base.title,
    dialogue: bp.bossDialogue || base.dialogue,
    bossModifier: bp.bossModifierOverride || base.bossModifier,
    maxHp: scaledHp,
    pointMultiplier: Number((base.pointMultiplier + stageId * 0.05).toFixed(2)),
  };
}

